import math

import numpy as np

from hardware_capability_check.kinematics import tool_down_rotation, wrap_to_pi


def test_zero_pose_matches_known_ur5e_position(profiles):
    k = profiles.robot.kinematics()
    p = k.fk(np.zeros(6))[:3, 3]
    # published UR5e zero-configuration TCP position (flange): x = a2+a3, y = -(d4+d6), z = d1-d5
    assert np.allclose(p, [-0.8172, -0.2329, 0.0628], atol=1e-4)


def test_ik_round_trip_many_random_poses(profiles):
    k = profiles.robot.kinematics()
    rng = np.random.default_rng(42)
    for _ in range(300):
        q = rng.uniform(-math.pi, math.pi, 6)
        T = k.fk(q)
        sols = k.ik(T)
        assert sols, "a pose generated by FK must have at least one IK solution"
        for s in sols:
            assert k.pose_error(k.fk(s), T) < 1e-6
        assert any(np.allclose([wrap_to_pi(a) for a in s], [wrap_to_pi(a) for a in q], atol=1e-5) for s in sols)


def test_unreachable_pose_has_no_solution(profiles):
    k = profiles.robot.kinematics()
    T = np.eye(4)
    T[:3, :3] = tool_down_rotation()
    T[:3, 3] = [2.0, 0.0, 0.3]
    assert k.ik(T) == []


def test_jacobian_matches_finite_differences(profiles):
    k = profiles.robot.kinematics()
    q = np.array([0.3, -1.1, 1.4, -0.7, 1.2, 0.5])
    J = k.jacobian(q)
    eps = 1e-6
    for i in range(6):
        dq = np.zeros(6)
        dq[i] = eps
        dp = (k.fk(q + dq)[:3, 3] - k.fk(q - dq)[:3, 3]) / (2 * eps)
        assert np.allclose(J[:3, i], dp, atol=1e-5)


def test_gravity_torque_scales_linearly_with_payload_and_is_zero_when_vertical(profiles):
    k = profiles.robot.kinematics()
    vertical = np.array([0.0, -math.pi / 2, 0.0, -math.pi / 2, 0.0, 0.0])  # arm straight up
    assert np.allclose(k.gravity_torques(vertical, 5.0), 0.0, atol=1e-6)
    q = np.array([0.0, -0.3, 0.2, -1.0, 1.0, 0.0])
    t0, t1, t2 = (k.gravity_torques(q, m, (0, 0, 0.1)) for m in (0.0, 1.0, 2.0))
    assert np.allclose(t2 - t0, 2 * (t1 - t0), atol=1e-9)


def test_horizontal_arm_static_torque_is_plausible(profiles):
    """Fully stretched horizontally with 5 kg: the shoulder torque must stay below the 150 Nm joint rating
    (UR rates this arm for 5 kg at 850 mm) while being clearly non-zero."""
    k = profiles.robot.kinematics()
    q = np.array([0.0, 0.0, 0.0, -math.pi / 2, 0.0, 0.0])
    tau = k.gravity_torques(q, 5.0, (0, 0, 0.1))
    assert 40 < abs(tau[1]) < 150
    assert abs(tau[4]) < 28


def test_limit_variants_respect_elbow_range(profiles):
    k = profiles.robot.kinematics()
    assert k.within_limits(np.array([0, 0, math.radians(150), 0, 0, 0]))
    assert not k.within_limits(np.array([0, 0, math.radians(170), 0, 0, 0]))
