class _M(BaseModel):
    model_config = ConfigDict(extra="forbid", populate_by_name=True)


def _finite(vals, what):
    for v in vals:
        if isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v):
            raise ValueError(f"{what}: values must be finite numbers")


class Workspace(_M):
    """Allowed TCP box in the robot base frame (m)."""
    frame_id: Literal["base"] = "base"
    x_m: tuple[float, float]
    y_m: tuple[float, float]
    z_m: tuple[float, float]

    @model_validator(mode="after")
    def _check(self):
        for ax in ("x_m", "y_m", "z_m"):
            lo, hi = getattr(self, ax)
            _finite([lo, hi], ax)
            if lo >= hi:
                raise ValueError(f"workspace {ax}: min must be < max")
        return self


class Limits(_M):
    verified: bool = False                 # set by a person who checked the numbers against the source
    source: str = Field(min_length=3)
    joint_min_rad: list[float]
    joint_max_rad: list[float]
    max_joint_speed_rad_s: list[float]
    max_joint_accel_rad_s2: float = Field(gt=0)
    max_tcp_speed_m_s: float = Field(gt=0)
    max_tcp_accel_m_s2: float = Field(gt=0)
    max_payload_kg: float = Field(gt=0)
    reach_m: float = Field(gt=0)

    @model_validator(mode="after")
    def _check(self):
        for name in ("joint_min_rad", "joint_max_rad", "max_joint_speed_rad_s"):
            _finite(getattr(self, name), name)
        _finite([self.max_joint_accel_rad_s2, self.max_tcp_speed_m_s, self.max_tcp_accel_m_s2,
                 self.max_payload_kg, self.reach_m], "limits")
        if len(self.joint_min_rad) != len(self.joint_max_rad):
            raise ValueError("joint_min_rad and joint_max_rad differ in length")
        if any(lo >= hi for lo, hi in zip(self.joint_min_rad, self.joint_max_rad)):
            raise ValueError("every joint_min_rad must be < joint_max_rad")
        if any(v <= 0 for v in self.max_joint_speed_rad_s):
            raise ValueError("max_joint_speed_rad_s must be positive")
        return self


class RobotEntry(_M):
    id: str = Field(pattern=_ID_RE)
    brand: str
    model: str
    dof: int = Field(ge=1, le=12)
    nominal_reach_m: float = Field(gt=0)
    nominal_payload_kg: float = Field(gt=0)
    library_url: str
    robodk_item_name: str
    station_name: Optional[str] = None
    library_file: Optional[str] = None     # file NAME inside robot_controller/stations/
    scene_file: Optional[str] = None       # file NAME inside robot_controller/config/ or config/scenes/
    default_workspace: Optional[Workspace] = None
    limits: Optional[Limits] = None
    notes: Optional[str] = None

    @field_validator("library_url")
    @classmethod
    def _url(cls, v):
        if not re.match(r"^https://[A-Za-z0-9.-]+\.[A-Za-z]{2,}(/[^\s\"'<>]*)?$", v):
            raise ValueError("library_url must be an https:// page (RoboDK library or manufacturer)")
        return v

    @field_validator("library_file")
    @classmethod
    def _lib(cls, v):
        if v is not None and not _LIBRARY_FILE_RE.match(v):
            raise ValueError("library_file must be a plain '<name>.robot' file name (it is looked up in "
                             "robot_controller/stations/; paths are not accepted)")
        return v

    @field_validator("scene_file")
    @classmethod
    def _scene(cls, v):
        if v is not None and not _SCENE_FILE_RE.match(v):
            raise ValueError("scene_file must be a plain '<name>.yaml' file name (looked up in "
                             "robot_controller/config/scenes/ then robot_controller/config/)")
        return v

    @model_validator(mode="after")
    def _dof(self):
        if self.limits is not None:
            for name in ("joint_min_rad", "joint_max_rad", "max_joint_speed_rad_s"):
                n = len(getattr(self.limits, name))
                if n != self.dof:
                    raise ValueError(f"{self.id}: limits.{name} has {n} values but dof={self.dof}")
        return self


class Catalog(_M):
    schema_: str = Field(default="motiq_robot_catalog/1", alias="schema")
    robots: list[RobotEntry]

    @model_validator(mode="after")
    def _unique(self):
        ids = [r.id for r in self.robots]
        if len(ids) != len(set(ids)):
            raise ValueError("robot ids must be unique")
        return self

    def get(self, robot_id: str) -> Optional[RobotEntry]:
        return next((r for r in self.robots if r.id == robot_id), None)


class Mounting(_M):
    orientation: Literal["upright", "wall", "ceiling"] = "upright"
    base_in_world_m: list[float] = Field(default_factory=lambda: [0.0, 0.0, 0.0], min_length=3, max_length=3)
    base_yaw_deg: float = 0.0
    table_surface_z_m: float = 0.0
    status: Literal["assumed", "measured"] = "assumed"

    @model_validator(mode="after")
    def _check(self):
        _finite([*self.base_in_world_m, self.base_yaw_deg, self.table_surface_z_m], "mounting")
        return self


class Hardware(_M):
    schema_: str = Field(default="motiq_hardware/2", alias="schema")
    active_robot: str
    backend: Literal["mock", "robodk_sim"] = "mock"
    speed_percent: float = Field(gt=0, le=100)
    mounting: Mounting = Field(default_factory=Mounting)
    components: list[Component] = Field(default_factory=list)   # every device: gripper, cameras, sensors, ...
    workspace_overrides: dict[str, Workspace] = Field(default_factory=dict)
    workspace_mode: Literal["box", "kinematic"] = "box"
    collision_policy: Literal["all", "table_and_tagged"] = "all"
    requirements: Optional[dict] = None    # GENERATED by apply(); ignored on input

    @field_validator("speed_percent")
    @classmethod
    def _speed(cls, v):
        _finite([v], "speed_percent")
        return v


