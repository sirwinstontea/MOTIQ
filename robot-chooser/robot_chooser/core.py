class Chooser:
    """All reads/writes go through one lock so the UI, CLI and tests never see half a change."""

    def __init__(self, root: Path | str = REPO_ROOT):
        self.root = Path(root).resolve()
        self.dir = self.root / "robot-chooser"
        self.catalog_path = self.dir / "catalog.yaml"
        self.hardware_path = self.dir / "hardware.yaml"
        self.ctrl = self.root / "robot_controller"
        self.ctrl_cfg = self.ctrl / "config"
        self.stations = self.ctrl / "stations"
        self.selection_path = self.ctrl_cfg / "selection.yaml"
        self.types_dir = self.dir / "hardware_types"
        self._lock = threading.RLock()

    # ---------------------------------------------------------------- load / save
    def load_catalog(self) -> Catalog:
        data = _read_yaml(self.catalog_path)
        try:
            return Catalog.model_validate(data)
        except ValidationError as e:
            raise ChooserError("CONFIG_INCOMPLETE", f"catalog.yaml: {_pydantic_msg(e)}", 500)

    def load_types(self) -> TypeRegistry:
        """Type files, re-read only when a file is added, removed or changed."""
        key = tuple((p.name, p.stat().st_mtime_ns, p.stat().st_size) for p in sorted(self.types_dir.glob("*.yaml")))
        cached = getattr(self, "_types_cache", None)
        if cached and cached[0] == key:
            return cached[1]
        try:
            reg = TypeRegistry.load(self.types_dir)
        except ValueError as e:
            raise ChooserError("CONFIG_INCOMPLETE", str(e), 500)
        self._types_cache = (key, reg)
        return reg

    def load_hardware(self) -> Hardware:
        data = _read_yaml(self.hardware_path)
        if isinstance(data, dict):
            data.pop("requirements", None)
            data = _migrate_v1(data)
        try:
            hw = Hardware.model_validate(data)
        except ValidationError as e:
            raise ChooserError("VALIDATION_ERROR", f"hardware.yaml: {_pydantic_msg(e)}", 500)
        self._check_components(hw, http=500)
        return hw

    def _check_components(self, hw: Hardware, http: int = 422) -> None:
        try:
            self.load_types().validate_all(hw.components)
        except ValueError as e:
            raise ChooserError("VALIDATION_ERROR", f"components: {e}", http)

    def _save_catalog(self, cat: Catalog) -> None:
        header = []
        if self.catalog_path.is_file():
            for line in self.catalog_path.read_text(encoding="utf-8").splitlines():
                if not line.startswith("#"):
                    break
                header.append(line)
        body = dump_yaml(cat.model_dump(mode="json", by_alias=True))
        _write(self.catalog_path, "\n".join(header) + ("\n" if header else "") + body)

    # ---------------------------------------------------------------- paths (allowlisted)
    def model_file(self, r: RobotEntry) -> Optional[Path]:
        return self.stations / r.library_file if r.library_file else None

    def scene_path(self, r: RobotEntry) -> Optional[Path]:
        if not r.scene_file:
            return None
        for p in (self.ctrl_cfg / "scenes" / r.scene_file, self.ctrl_cfg / r.scene_file):
            if p.is_file():
                return p
        return self.ctrl_cfg / "scenes" / r.scene_file   # reported as missing

    # ---------------------------------------------------------------- evaluation
    def evaluate(self, cat: Catalog, hw: Hardware, robot_id: Optional[str] = None) -> dict:
        """Check one robot (default: the active one) against the cell setup. Pure: writes nothing."""
        rid = robot_id or hw.active_robot
        r = cat.get(rid)
        issues: list[dict] = []

        def add(level, code, msg):
            issues.append({"level": level, "code": code, "message": msg})

        if r is None:
            add("blocker", "UNKNOWN_ROBOT", f"'{rid}' is not in catalog.yaml")
            return self._report(rid, None, hw, issues, None)

        tag = r.model
        mf = self.model_file(r)
        model_file_ok = bool(mf and mf.is_file())
        if not model_file_ok:
            what = (f"robot_controller/stations/{r.library_file} not found" if r.library_file
                    else "no RoboDK model file registered")
            msg = f"{tag}: {what}. Download it once from {r.library_url} and save it in robot_controller/stations/."
            add("blocker" if hw.backend == "robodk_sim" else "warning", "MODEL_FILE_MISSING",
                msg if hw.backend == "robodk_sim" else msg + " (needed for robodk_sim; mock runs without it)")

        if r.limits is None:
            add("blocker", "CONFIG_INCOMPLETE", f"{tag}: joint limits / speeds not configured. Fill them in from the "
                "manufacturer datasheet or the RoboDK model (Joints / JointLimits), with a source.")
        elif not r.limits.verified:
            add("blocker", "CONFIG_INCOMPLETE", f"{tag}: limits are not marked verified (set limits.verified: true "
                f"only after checking them against: {r.limits.source})")

        sp = self.scene_path(r)
        scene_data = None
        if sp is None:
            add("blocker", "CONFIG_INCOMPLETE", f"{tag}: no scene (taught targets) for this robot. Create "
                f"robot_controller/config/scenes/{r.id}.yaml - do not reuse another robot's targets.")
        elif not sp.is_file():
            add("blocker", "CONFIG_INCOMPLETE", f"{tag}: scene file {r.scene_file} not found")
        else:
            try:
                scene_data = _read_yaml(sp)
            except ChooserError as e:
                add("blocker", "CONFIG_INCOMPLETE", e.message)

        ws = hw.workspace_overrides.get(r.id) or r.default_workspace
        if ws is None:
            add("blocker", "CONFIG_INCOMPLETE", f"{tag}: no workspace box for this robot's cell "
                "(catalog default_workspace or hardware.yaml workspace_overrides)")

        reach = r.limits.reach_m if r.limits else r.nominal_reach_m
        payload = r.limits.max_payload_kg if r.limits else r.nominal_payload_kg
        tooling = _analyse(self.load_types(), hw.components)
        issues.extend(tooling["issues"])
        tcp_len = math.dist([0, 0, 0], tooling["tcp_offset_m_rad"][:3])
        budget = round(payload - tooling["carried_mass_kg"], 4)
        if budget <= 0:
            add("blocker", "PAYLOAD", f"{tag}: hardware on the arm weighs {tooling['carried_mass_kg']} kg and "
                f"leaves no payload (rated {payload} kg)")

        limit_r = reach + tcp_len
        if ws is not None:
            far = max(math.dist([0, 0, 0], [x, y, z]) for x in ws.x_m for y in ws.y_m for z in ws.z_m)
            if far > limit_r:
                add("warning", "WORKSPACE", f"{tag}: workspace corner {far:.3f} m from the base exceeds nominal "
                    f"reach + TCP ({limit_r:.3f} m). Orientative only - the controller's IK/path check decides.")
        if isinstance(scene_data, dict):
            for name, t in (scene_data.get("targets") or {}).items():
                if not isinstance(t, dict):
                    continue
                j = t.get("joints_rad")
                if j is not None and len(j) != r.dof:
                    add("blocker", "MODEL_MISMATCH", f"{tag}: target '{name}' has {len(j)} joint values, "
                        f"robot has {r.dof} - re-teach it, never truncate or pad")
                p = t.get("pose_m_rad")
                if isinstance(p, list) and len(p) >= 3:
                    d = math.dist([0, 0, 0], p[:3])
                    if d > limit_r:
                        add("warning", "WORKSPACE", f"{tag}: target '{name}' is {d:.3f} m from the base "
                            f"(> reach + TCP {limit_r:.3f} m) - probably unreachable")

        if r.dof < 6:
            add("info", "ORIENTATION", f"{tag} has {r.dof} joints: not every 6-DOF tool pose is possible. "
                "Rotations are decided per target by IK, not rejected wholesale.")
        if hw.mounting.orientation != "upright":
            add("warning", "MOUNTING", f"{hw.mounting.orientation} mounting: scene and workspace must be expressed "
                "for that mounting (demo scenes assume upright)")
        if hw.mounting.status == "assumed":
            add("info", "MOUNTING", "robot base pose in the cell is assumed, not measured")
        generated = None
        if not any(i["level"] == "blocker" for i in issues):
            try:
                generated = self._build_configs(r, hw, ws, scene_data)
            except ChooserError as e:
                add("blocker", e.code, e.message)
        return self._report(rid, r, hw, issues, generated, model_file_ok=model_file_ok,
                            payload_budget_kg=budget, carried_mass_kg=tooling["carried_mass_kg"],
                            reach_m=reach, tcp_length_m=round(tcp_len, 4), end_effector=tooling["end_effector"],
                            components=tooling["connections"], workspace=ws)

    def _report(self, rid, r, hw, issues, generated, **extra) -> dict:
        blockers = [i for i in issues if i["level"] == "blocker"]
        codes = {i["code"] for i in blockers}
        if not blockers:
            label = "Ready"
        elif "MODEL_FILE_MISSING" in codes:
            label = "Model missing"
        elif "UNKNOWN_ROBOT" in codes:
            label = "Unknown"
        else:
            label = "Config incomplete"
        ws = extra.pop("workspace", None)
        rep = {
            "robot_id": rid,
            "robot": f"{r.brand} {r.model}" if r else None,
            "dof": r.dof if r else None,
            "backend": hw.backend,
            "simulation_only": True,
            "status": "READY" if not blockers else "BLOCKED",
            "label": label,
            "limits_verified": bool(r and r.limits and r.limits.verified),
            "config_complete": not (codes & {"CONFIG_INCOMPLETE", "MODEL_MISMATCH", "UNKNOWN_ROBOT"}),
            "blockers": blockers,
            "warnings": [i for i in issues if i["level"] == "warning"],
            "notes": [i for i in issues if i["level"] == "info"],
            **extra,
        }
        if ws is not None:
            rep["workspace"] = ws.model_dump(mode="json")
        rep["_generated"] = generated
        return rep

    # ---------------------------------------------------------------- controller config generation
    def _controller_models(self):
        for d in (self.ctrl, REPO_ROOT / "robot_controller"):
            if (d / "robot_control").is_dir() and str(d) not in sys.path:
                sys.path.insert(0, str(d))
        try:
            from robot_control import config as rc          # the controller's own validators
            from robot_control.models import RobotControlError
        except Exception as e:                                # fail closed: no unvalidated output
            raise ChooserError("CONFIG_INCOMPLETE", f"cannot import robot_control to validate the generated "
                               f"configs ({e.__class__.__name__}: {e})", 500)
        return rc, RobotControlError

    def robot_config_dict(self, r: RobotEntry, hw: Hardware) -> dict:
        lim = r.limits.model_dump(mode="json")
        lim.pop("verified")
        tooling = _analyse(self.load_types(), hw.components)
        kind = tooling["gripper_kind"]
        caps = ["named_targets", "path_check"] + (["symbolic_gripper"] if kind == "symbolic" else [])
        return {
            "model": r.model,
            "dof": r.dof,
            "backend": hw.backend,
            "station_name": r.station_name or f"MOTIQ {r.model} Demo",
            "station_path": f"stations/{r.model}_demo.rdk",
            "robot_library_file": f"stations/{r.library_file}" if r.library_file else None,
            "robot_item_name": r.robodk_item_name,
            "base_frame": f"{r.model} Base",
            "tool_frame": "Gripper TCP",
            "gripper_kind": kind,
            "tcp_offset_m_rad": list(tooling["tcp_offset_m_rad"]),
            "tool_mass_kg": tooling["carried_mass_kg"],          # everything the arm carries
            "limits": lim,
            "capabilities": caps,
        }

    def _build_configs(self, r: RobotEntry, hw: Hardware, ws: Workspace, scene_data: dict) -> dict:
        rc, RCE = self._controller_models()
        scene_data = {**scene_data, "collision_policy": hw.collision_policy}
        safety_src = self.ctrl_cfg / "safety.example.yaml"
        safety = _read_yaml(safety_src)
        if not isinstance(safety, dict):
            raise ChooserError("CONFIG_INCOMPLETE", "safety.example.yaml must be a mapping", 500)
        for k in ("tcp_speed_m_s", "tcp_accel_m_s2", "joint_speed_rad_s", "joint_accel_rad_s2"):
            safety.pop(k, None)
        safety["speed_percent_of_model_max"] = hw.speed_percent
        safety["workspace"] = ws.model_dump(mode="json")
        if hw.workspace_mode == "kinematic":
            safety["workspace"]["mode"] = "kinematic"
            # Retain the configured TCP clearance above the table; remove lateral and upper box restrictions.
            safety["require_path_check"] = True
            safety["require_collision_geometry"] = True
            if hw.collision_policy == "table_and_tagged":
                table = scene_data.get("station_geometry", {}).get(scene_data.get("table_geometry", "table"))
                if table is None or any(abs(v) > 1e-8 for v in table["pose_m_rad"][3:]):
                    raise ChooserError("CONFIG_INCOMPLETE", "contact policy requires a configured horizontal table")
                safety["workspace"]["z_m"][0] = table["pose_m_rad"][2] + table["size_m"][2]
        safety["allowed_backends"] = [b for b in safety.get("allowed_backends", []) if b in ALLOWED_BACKENDS] \
            or list(ALLOWED_BACKENDS)
        robot = self.robot_config_dict(r, hw)
        try:
            rcfg = rc.RobotConfig.model_validate(robot)
            scfg = rc.SafetyConfig.model_validate(safety)
            sccfg = rc.SceneConfig.model_validate(scene_data)
            rc.cross_validate(rcfg, scfg, sccfg)
        except ValidationError as e:
            raise ChooserError("CONFIG_INCOMPLETE", f"{r.model}: controller rejects the generated config: "
                               f"{_pydantic_msg(e)}")
        except RCE as e:
            raise ChooserError("CONFIG_INCOMPLETE", f"{r.model}: controller cross-check failed: {e}")
        if hw.backend not in scfg.allowed_backends:
            raise ChooserError("CONFIG_INCOMPLETE", f"backend {hw.backend} is not allowed by the safety config")
        return {"robot": robot, "safety": safety, "scene": scene_data}

    # ---------------------------------------------------------------- state for UI / CLI
    def state(self) -> dict:
        with self._lock:
            cat, hw = self.load_catalog(), self.load_hardware()
            rows = []
            for r in cat.robots:
                rep = self.evaluate(cat, hw, r.id)
                mf = self.model_file(r)
                rows.append({**r.model_dump(mode="json"), "status": rep["label"],
                             "active": r.id == hw.active_robot,
                             "model_file_available": bool(mf and mf.is_file()),
                             "limits_verified": rep["limits_verified"], "config_complete": rep["config_complete"]})
            report = self.evaluate(cat, hw)
            report.pop("_generated", None)
            sel = _read_yaml(self.selection_path) if self.selection_path.is_file() else None
            return {"catalog": rows, "hardware": hw.model_dump(mode="json", by_alias=True, exclude={"requirements"}),
                    "report": report, "selection": sel, "types": self.load_types().dump()}

    def filter_catalog(self, text: str = "", brand: Optional[str] = None, dof: Optional[int] = None) -> list[str]:
        t = text.lower().strip()
        out = []
        for r in self.load_catalog().robots:
            hay = f"{r.id} {r.brand} {r.model}".lower()
            if t and t not in hay:
                continue
            if brand and brand.lower() not in r.brand.lower():
                continue
            if dof is not None and r.dof != dof:
                continue
            out.append(r.id)
        return out

    # ---------------------------------------------------------------- mutations (each one re-applies)
    def select(self, robot_id: str) -> dict:
        with self._lock:
            cat = self.load_catalog()
            if not isinstance(robot_id, str) or cat.get(robot_id) is None:
                raise ChooserError("UNKNOWN_ROBOT", f"unknown robot_id {robot_id!r}; known: "
                                   + ", ".join(r.id for r in cat.robots), 404)
            hw = self.load_hardware().model_copy(update={"active_robot": robot_id})
            return self._commit(cat, hw)

    def update_hardware(self, patch: dict) -> dict:
        if not isinstance(patch, dict):
            raise ChooserError("VALIDATION_ERROR", "body must be a JSON object")
        patch = {k: v for k, v in patch.items() if k not in ("requirements", "schema")}
        with self._lock:
            cat, hw = self.load_catalog(), self.load_hardware()
            merged = _deep_merge(hw.model_dump(mode="json", by_alias=True, exclude={"requirements"}), patch)
            if "components" in patch:
                merged["components"] = patch["components"]      # lists are replaced, not merged
            try:
                new = Hardware.model_validate(merged)
            except ValidationError as e:
                raise ChooserError("VALIDATION_ERROR", _pydantic_msg(e))
            self._check_components(new)
            if cat.get(new.active_robot) is None:
                raise ChooserError("UNKNOWN_ROBOT", f"unknown robot_id {new.active_robot!r}", 404)
            unknown_ws = set(new.workspace_overrides) - {r.id for r in cat.robots}
            if unknown_ws:
                raise ChooserError("UNKNOWN_ROBOT", f"workspace_overrides for unknown robots: {sorted(unknown_ws)}", 404)
            return self._commit(cat, new)

    # ---------------------------------------------------------------- components (any hardware)
    def _set_components(self, comps: list) -> dict:
        cat, hw = self.load_catalog(), self.load_hardware()
        try:
            new = Hardware.model_validate({**hw.model_dump(mode="json", by_alias=True, exclude={"requirements"}),
                                           "components": comps})
        except ValidationError as e:
            raise ChooserError("VALIDATION_ERROR", _pydantic_msg(e))
        self._check_components(new)
        return self._commit(cat, new)

    def add_component(self, comp: dict) -> dict:
        if not isinstance(comp, dict):
            raise ChooserError("VALIDATION_ERROR", "body must be a JSON object")
        with self._lock:
            cur = [c.model_dump(mode="json") for c in self.load_hardware().components]
            if any(c["id"] == comp.get("id") for c in cur):
                raise ChooserError("DUPLICATE_COMPONENT", f"component id {comp.get('id')!r} already exists", 409)
            return self._set_components([*cur, comp])

    def update_component(self, comp_id: str, patch: dict) -> dict:
        if not isinstance(patch, dict):
            raise ChooserError("VALIDATION_ERROR", "body must be a JSON object")
        if "id" in patch and patch["id"] != comp_id:
            raise ChooserError("VALIDATION_ERROR", "a component id cannot be changed (remove and add it)")
        with self._lock:
            cur = [c.model_dump(mode="json") for c in self.load_hardware().components]
            idx = next((i for i, c in enumerate(cur) if c["id"] == comp_id), None)
            if idx is None:
                raise ChooserError("UNKNOWN_COMPONENT", f"unknown component {comp_id!r}", 404)
            cur[idx] = _deep_merge(cur[idx], patch)
            return self._set_components(cur)

    def remove_component(self, comp_id: str) -> dict:
        with self._lock:
            cur = [c.model_dump(mode="json") for c in self.load_hardware().components]
            if not any(c["id"] == comp_id for c in cur):
                raise ChooserError("UNKNOWN_COMPONENT", f"unknown component {comp_id!r}", 404)
            children = [c["id"] for c in cur if c["attached_to"] == comp_id]
            if children:
                raise ChooserError("COMPONENT_IN_USE", f"{comp_id} carries {children}; move or remove them first", 409)
            return self._set_components([c for c in cur if c["id"] != comp_id])

    def update_robot(self, robot_id: str, patch: dict) -> dict:
        if not isinstance(patch, dict):
            raise ChooserError("VALIDATION_ERROR", "body must be a JSON object")
        bad = set(patch) - EDITABLE_ROBOT_FIELDS
        if bad:
            raise ChooserError("VALIDATION_ERROR", f"not editable here: {sorted(bad)} (editable: "
                               f"{sorted(EDITABLE_ROBOT_FIELDS)}; brand/model/dof are edited in catalog.yaml)")
        with self._lock:
            cat = self.load_catalog()
            r = cat.get(robot_id)
            if r is None:
                raise ChooserError("UNKNOWN_ROBOT", f"unknown robot_id {robot_id!r}", 404)
            cur = r.model_dump(mode="json")
            for k, v in patch.items():
                cur[k] = _deep_merge(cur[k], v) if isinstance(v, dict) and isinstance(cur.get(k), dict) else v
            try:
                new_r = RobotEntry.model_validate(cur)
                new_cat = Catalog.model_validate({"schema": cat.schema_,
                                                  "robots": [new_r if x.id == robot_id else x for x in cat.robots]})
            except ValidationError as e:
                raise ChooserError("VALIDATION_ERROR", _pydantic_msg(e))
            self._save_catalog(new_cat)
            return self._commit(new_cat, self.load_hardware())

    def add_robot(self, entry: dict) -> dict:
        """Add any arm to the catalog. It starts BLOCKED until its limits, scene and workspace are filled in."""
        if not isinstance(entry, dict):
            raise ChooserError("VALIDATION_ERROR", "body must be a JSON object")
        with self._lock:
            cat = self.load_catalog()
            if cat.get(entry.get("id")) is not None:
                raise ChooserError("DUPLICATE_ROBOT", f"robot id {entry.get('id')!r} already exists", 409)
            try:
                new_r = RobotEntry.model_validate({"robodk_item_name": entry.get("model"), **entry})
                new_cat = Catalog.model_validate({"schema": cat.schema_, "robots": [*cat.robots, new_r]})
            except ValidationError as e:
                raise ChooserError("VALIDATION_ERROR", _pydantic_msg(e))
            self._save_catalog(new_cat)
            return self._commit(new_cat, self.load_hardware())

    def remove_robot(self, robot_id: str) -> dict:
        with self._lock:
            cat, hw = self.load_catalog(), self.load_hardware()
            if cat.get(robot_id) is None:
                raise ChooserError("UNKNOWN_ROBOT", f"unknown robot_id {robot_id!r}", 404)
            if hw.active_robot == robot_id:
                raise ChooserError("ROBOT_ACTIVE", f"{robot_id} is the active robot; select another one first", 409)
            new_cat = Catalog.model_validate({"schema": cat.schema_,
                                              "robots": [r for r in cat.robots if r.id != robot_id]})
            hw = hw.model_copy(update={"workspace_overrides": {k: v for k, v in hw.workspace_overrides.items()
                                                               if k != robot_id}})
            self._save_catalog(new_cat)
            return self._commit(new_cat, hw)

    def apply(self) -> dict:
        with self._lock:
            return self._commit(self.load_catalog(), self.load_hardware())

    # ---------------------------------------------------------------- write everything
    def _commit(self, cat: Catalog, hw: Hardware) -> dict:
        report = self.evaluate(cat, hw)
        generated = report.pop("_generated")
        prev = _read_yaml(self.selection_path) if self.selection_path.is_file() else {}
        version = int((prev or {}).get("selection_version", 0)) + 1
        now = _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat()
        files = []

        # per-robot controller profiles for every robot whose limits are complete + verified
        robots_dir = self.ctrl_cfg / "robots"
        masses_unknown = bool(_analyse(self.load_types(), hw.components)["unknown_mass"])   # never understate
        for r in cat.robots:
            target = robots_dir / f"{r.id}.yaml"
            if r.limits is not None and r.limits.verified and not masses_unknown:
                rd = self.robot_config_dict(r, hw)
                _write(target, f"{GENERATED_MARK} from robot-chooser/catalog.yaml + hardware.yaml - do not edit.\n"
                       f"# {r.brand} {r.model}. Simulation only. Edit the catalog / hardware.yaml instead.\n"
                       + dump_yaml(rd))
            elif target.is_file() and target.read_text(encoding="utf-8").startswith(GENERATED_MARK):
                target.unlink()
        known = {r.id for r in cat.robots}
        for old in robots_dir.glob("*.yaml") if robots_dir.is_dir() else []:
            if old.stem not in known and old.read_text(encoding="utf-8").startswith(GENERATED_MARK):
                old.unlink()                                   # robot removed from the catalog

        active = {"robot": self.ctrl_cfg / "robot.yaml", "safety": self.ctrl_cfg / "safety.yaml",
                  "scene": self.ctrl_cfg / "scene.yaml"}
        if generated:
            r = cat.get(hw.active_robot)
            for key, p in active.items():
                if p.is_file() and not p.read_text(encoding="utf-8").startswith(GENERATED_MARK):
                    bak = p.with_name(p.name + ".bak")
                    if not bak.exists():
                        p.replace(bak)                           # keep a hand-written file once
                head = (f"{GENERATED_MARK} for {r.brand} {r.model} ({r.id}), selection_version {version}, {now}.\n"
                        "# Do not edit: change robot-chooser/hardware.yaml or catalog.yaml and re-apply.\n")
                _write(p, head + dump_yaml(generated[key]))
                files.append(str(p.relative_to(self.root)).replace("\\", "/"))
        else:
            # never leave a previous robot's generated files active (no silent fallback)
            for p in active.values():
                if p.is_file() and p.read_text(encoding="utf-8").startswith(GENERATED_MARK):
                    p.unlink()

        r = cat.get(hw.active_robot)
        selection = {
            "robot_id": hw.active_robot,
            "model": r.model if r else None,
            "dof": r.dof if r else None,
            "backend": hw.backend,
            "simulation_only": True,
            "status": report["status"],
            "selection_version": version,
            "generated_at": now,
            "files": files,
            "blockers": [f"{b['code']}: {b['message']}" for b in report["blockers"]],
        }
        _write(self.selection_path, f"{GENERATED_MARK}: the robot the controller must load. Read by "
               "robot_control.cli; a BLOCKED selection makes it refuse to start.\n" + dump_yaml(selection))

        report["selection_version"] = version
        report["generated_files"] = files
        report["generated_at"] = now
        _write(self.hardware_path, render_hardware(hw, report))
        return self.state()


# --------------------------------------------------------------------------------------------------
# hardware.yaml renderer (keeps the explanatory comments; requirements block is regenerated)
# --------------------------------------------------------------------------------------------------


_HEADER = """\
# MOTIQ hardware setup = the hardware requirements document of the arm cell.
# Change it here (then run: python -m robot_chooser apply) or in the UI (python -m robot_chooser serve).
# Everything above the `requirements:` block is input; that block is regenerated on every apply.
# Units: m, rad, kg (deg only where the key says so). Simulation only: no physical robot is ever selected.
"""


def _kv(key: str, value, comment: str = "", indent: int = 0) -> str:
    line = f"{' ' * indent}{key}: {_flow(value)}"
    return f"{line:<{max(44, len(line) + 2)}}# {comment}" if comment else line


def render_hardware(hw: Hardware, report: dict) -> str:
    m = hw.mounting
    comps = dump_yaml([c.model_dump(mode="json") for c in hw.components]) if hw.components else "[]\n"
    ws = dump_yaml({k: v.model_dump(mode="json") for k, v in hw.workspace_overrides.items()}) \
        if hw.workspace_overrides else "{}\n"
    req = {k: v for k, v in report.items() if not k.startswith("_")}
    lines = [
        _HEADER.rstrip("\n"),
        _kv("schema", hw.schema_),
        "",
        _kv("active_robot", hw.active_robot, "one id from catalog.yaml"),
        _kv("backend", hw.backend, "mock (no RoboDK) | robodk_sim (RoboDK, RUNMODE_SIMULATE)"),
        _kv("speed_percent", hw.speed_percent, "% of the ACTIVE robot's verified maximums"),
        _kv("workspace_mode", hw.workspace_mode, "box | kinematic (model IK + collisions; retain table clearance)"),
        _kv("collision_policy", hw.collision_policy, "all | table_and_tagged (simulation contact policy)"),
        "",
        "mounting:",
        _kv("orientation", m.orientation, "upright | wall | ceiling", 2),
        _kv("base_in_world_m", list(m.base_in_world_m), "robot base in the cell frame", 2),
        _kv("base_yaw_deg", m.base_yaw_deg, indent=2),
        _kv("table_surface_z_m", m.table_surface_z_m, indent=2),
        _kv("status", m.status, "assumed | measured", 2),
        "",
        "# Every device in the cell, one entry each. type = a file in hardware_types/ (fields, units, drivers).",
        "# attached_to: cell | arm | <component id> (chains: arm -> tool_changer -> gripper -> camera).",
        "# Everything carried by the arm counts against its payload; the end effector sets the TCP.",
        "# status: placeholder | datasheet | measured. driver: how it is connected (see its type file).",
        "components:",
        _indent(comps, 2),
        "",
        f"{'workspace_overrides:':<44}# per robot id; empty = catalog default_workspace",
        _indent(ws, 2),
        "",
        "# " + "-" * 98,
        "# GENERATED by robot-chooser on apply - do not edit by hand.",
        "# status READY = controller files generated and validated by robot_control; BLOCKED = they were not.",
        "# " + "-" * 98,
        "requirements:",
        _indent(dump_yaml(req), 2),
        "",
    ]
    return "\n".join(lines)
