"""robot-chooser core.

Two hand-editable YAML files are the source of truth:

* ``robot-chooser/catalog.yaml``  - robot FACTS (DOF, limits, RoboDK model file, per-robot scene/workspace)
* ``robot-chooser/hardware.yaml`` - the CELL SETUP (active robot, backend, speed, tool, mounting, cameras)

``Chooser.apply()`` checks the combination, writes a generated ``requirements`` block back into
hardware.yaml (what is ready, what blocks, what is only assumed) and - only when nothing blocks -
generates the controller files ``robot_controller/config/{robot,safety,scene}.yaml``, validated with the
controller's own pydantic models and ``cross_validate``. ``config/selection.yaml`` records the choice so
the controller refuses to start on a blocked selection instead of silently falling back to the UR5e
example files.

Simulation only: the chooser can select the ``mock`` or ``robodk_sim`` backend, never a physical one.
"""
from __future__ import annotations

import datetime as _dt
import math
import re
import sys
import threading
from pathlib import Path
from typing import Any, Literal, Optional

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator, model_validator

from .components import Component, TypeRegistry
from .tooling import analyse_components as _analyse, migrate_v1 as _migrate_v1

CHOOSER_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = CHOOSER_DIR.parent

ALLOWED_BACKENDS = ("mock", "robodk_sim")          # never physical_disabled / ursim_sync from here
GENERATED_MARK = "# GENERATED by robot-chooser"
_LIBRARY_FILE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 ._\-]*\.robot$")
_SCENE_FILE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._\-]*\.ya?ml$")
_ID_RE = r"^[a-z0-9][a-z0-9_]*$"
EDITABLE_ROBOT_FIELDS = {"library_file", "scene_file", "default_workspace", "limits", "station_name", "notes"}


class ChooserError(Exception):
    """Typed error. ``http`` is the status the API returns."""

    def __init__(self, code: str, message: str, http: int = 422):
        super().__init__(message)
        self.code, self.message, self.http = code, message, http

    def as_dict(self) -> dict:
        return {"code": self.code, "message": self.message}


