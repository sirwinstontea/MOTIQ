class _Dumper(yaml.SafeDumper):
    pass


def _repr_seq(d, data):
    flow = all(not isinstance(x, (list, tuple, dict)) for x in data)
    return d.represent_sequence("tag:yaml.org,2002:seq", list(data), flow_style=flow)


_Dumper.add_representer(list, _repr_seq)
_Dumper.add_representer(tuple, _repr_seq)


def dump_yaml(obj) -> str:
    return yaml.dump(obj, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=110)


def _flow(v) -> str:
    """One-line YAML for a scalar or a list (used inside the commented hardware.yaml template)."""
    return yaml.dump(v, Dumper=_Dumper, default_flow_style=True, width=1000, allow_unicode=True) \
        .strip().removesuffix("...").strip()


def _indent(text: str, n: int) -> str:
    pad = " " * n
    return "\n".join(pad + line if line else line for line in text.rstrip("\n").splitlines())


def _read_yaml(p: Path) -> Any:
    try:
        return yaml.safe_load(p.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise ChooserError("CONFIG_INCOMPLETE", f"file not found: {p}", 500)
    except yaml.YAMLError as e:
        raise ChooserError("CONFIG_INCOMPLETE", f"invalid YAML in {p.name}: {e}", 500)


def _write(p: Path, text: str) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_name(p.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(p)                                     # atomic on the same volume


def _deep_merge(base: dict, patch: dict) -> dict:
    out = dict(base)
    for k, v in patch.items():
        out[k] = _deep_merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def _pydantic_msg(e: ValidationError) -> str:
    return "; ".join(f"{'.'.join(str(x) for x in err['loc']) or 'value'}: {err['msg']}" for err in e.errors())


