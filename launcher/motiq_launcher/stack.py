"""Start and stop the MOTIQ services. A cross-platform port of bridge/start_stack.sh (non-SIM path) plus Expo."""
from __future__ import annotations

import os
import re
import socket
import subprocess
import threading
import time
import urllib.error
import urllib.request
from pathlib import Path

from . import configure, detect, paths
from .xai_proxy import XaiProxy

NO_WINDOW = detect.NO_WINDOW
LABELS = {"chooser": "Robot chooser", "vision": "Vision server", "teach": "Teach server", "robodk": "RoboDK",
          "controller": "Robot controller", "bridge": "Arm bridge", "expo": "MOTIQ app"}


def port_open(port: int, host: str = "127.0.0.1") -> bool:
    with socket.socket() as s:
        s.settimeout(0.4)
        return s.connect_ex((host, port)) == 0


def http_ok(url: str, timeout: float = 1.5) -> bool:
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            return r.status < 500
    except urllib.error.HTTPError as e:      # e.g. the bridge answers 401 without X-Bridge-Key: it is up
        return e.code < 500
    except Exception:
        return False


class Service:
    def __init__(self, name: str, cmd: list, cwd: Path, health: str, env: dict | None = None, port: int = 0):
        self.name, self.cmd, self.cwd, self.health, self.port = name, [str(c) for c in cmd], cwd, health, port
        self.env = env
        self.proc: subprocess.Popen | None = None
        self.log = paths.LOGS / f"{name}.log"

    def start(self) -> None:
        paths.LOGS.mkdir(parents=True, exist_ok=True)
        out = self.log.open("w", encoding="utf-8", errors="replace")
        out.write("$ " + " ".join(self.cmd) + "\n")
        out.flush()
        self.proc = subprocess.Popen(self.cmd, cwd=str(self.cwd), env=self.env, stdout=out, stderr=subprocess.STDOUT,
                                     stdin=subprocess.DEVNULL, creationflags=NO_WINDOW)

    def alive(self) -> bool:
        return self.proc is not None and self.proc.poll() is None

    def healthy(self) -> bool:
        return http_ok(self.health)

    def stop(self) -> None:
        if not self.alive():
            return
        assert self.proc
        if paths.WIN:      # npx/node and uvicorn spawn children: take the whole tree down
            subprocess.call(["taskkill", "/PID", str(self.proc.pid), "/T", "/F"], stdout=subprocess.DEVNULL,
                            stderr=subprocess.DEVNULL, creationflags=NO_WINDOW)
        else:
            self.proc.terminate()
        try:
            self.proc.wait(10)
        except subprocess.TimeoutExpired:
            self.proc.kill()

    def tail(self, n: int = 30) -> list[str]:
        try:
            return self.log.read_text(encoding="utf-8", errors="replace").splitlines()[-n:]
        except OSError:
            return []


def _station_path() -> Path | None:
    """robot_controller/config/robot.yaml (generated by robot-chooser) -> the RoboDK station it expects."""
    try:
        m = re.search(r"^station_path:\s*(\S+)", (paths.RC / "config" / "robot.yaml").read_text(encoding="utf-8"), re.M)
    except OSError:
        return None
    return paths.RC / m.group(1).strip("'\"") if m else None


class Stack:
    def __init__(self):
        self.services: dict[str, Service] = {}
        self.lock = threading.Lock()
        self.cfg: dict = {}
        self.plan: dict = {}
        self.app_url = ""
        self.phone_url = ""
        self.xai = XaiProxy()

    # -------------------------------------------------------------- build
    def _services(self, cfg: dict, plan: dict, node_exe: str, clear_cache: bool) -> list[Service]:
        p, bind = cfg["ports"], plan["bind"]
        out: list[Service] = []
        if plan["python"]:
            rc, cv = str(paths.RC_PY), str(paths.CV_PY)
            vision_file = paths.RC / "runs" / "vision_bridge.json"
            out.append(Service("chooser", [rc, "-m", "robot_chooser", "serve", "--host", bind, "--port", p["chooser"]],
                               paths.CHOOSER, f"http://127.0.0.1:{p['chooser']}/api/state", port=p["chooser"]))
            vcmd = [cv, "-m", "vision.eyes.cli", "run", "--host", bind, "--port", p["vision"], "--mode", plan["vision_mode"],
                    "--controller", f"http://127.0.0.1:{p['controller']}"]
            if plan["vision_mode"] == "webcam":
                vcmd += ["--device", cfg["camera"].get("device") or "0"]
            # no --robot-ip: its read-only UR telemetry needs ur_rtde, which the vision requirements don't install
            senv = dict(os.environ, **configure.secret_env(cfg))   # the xAI key only in these processes' memory
            out.append(Service("vision", vcmd, paths.CV, f"http://127.0.0.1:{p['vision']}/health", env=senv,
                               port=p["vision"]))
            out.append(Service("teach", [cv, paths.TEACH, "--host", bind, "--port", p["teach"]], paths.CV,
                               f"http://127.0.0.1:{p['teach']}/health", env=senv, port=p["teach"]))
            out.append(Service("controller", [rc, "-m", "robot_control.cli", "serve", "--backend", plan["backend"],
                                              "--detector", "vision_file", "--vision-file", vision_file,
                                              "--port", p["controller"]],
                               paths.RC, f"http://127.0.0.1:{p['controller']}/health", port=p["controller"]))
            benv = dict(os.environ, BRIDGE_KEY=cfg["bridge_key"], REAL_ARM="1" if plan["real_arm"] else "0")
            if plan["real_arm"]:
                benv["MOTIQ_UR_JOG"] = cfg.get("ur_jog") or ""
                benv["MOTIQ_UR_HOST"] = cfg.get("robot_ip") or ""
            else:   # simulation: never load the physical UR driver, even if ../ur_manual/ur_jog.py exists
                benv["MOTIQ_UR_JOG"] = str(paths.STATE / "no-physical-arm" / "ur_jog.py")
            out.append(Service("bridge", [rc, paths.BRIDGE, "--host", bind, "--port", p["bridge"],
                                          "--controller", f"http://127.0.0.1:{p['controller']}",
                                          "--vision", f"http://127.0.0.1:{p['vision']}", "--vision-file", vision_file,
                                          "--robot-chooser", f"http://127.0.0.1:{p['chooser']}"],
                               paths.ROOT, f"http://127.0.0.1:{p['bridge']}/health", env=benv, port=p["bridge"]))
        expo_cli = paths.APP / "node_modules" / "expo" / "bin" / "cli"
        eenv = dict(os.environ, CI="1", BROWSER="none", EXPO_NO_TELEMETRY="1")
        eenv["PATH"] = str(Path(node_exe).parent) + os.pathsep + eenv.get("PATH", "")
        ecmd = [node_exe, expo_cli, "start", "--port", p["expo"], "--host",
                "lan" if plan["bind"] == "0.0.0.0" else "localhost"]
        if clear_cache:
            ecmd.append("--clear")          # EXPO_PUBLIC_* values are inlined: a new config needs a fresh bundle
        out.append(Service("expo", ecmd, paths.APP, f"http://127.0.0.1:{p['expo']}/", env=eenv, port=p["expo"]))
        return out

    # -------------------------------------------------------------- run
    def start(self, cfg: dict, plan: dict, node_exe: str, clear_cache: bool, log=print) -> None:
        self.stop(log)
        self.cfg, self.plan = cfg, plan
        p = cfg["ports"]
        self.app_url = f"http://localhost:{p['expo']}"
        self.phone_url = f"exp://{plan['host']}:{p['expo']}" if plan["bind"] == "0.0.0.0" else ""
        busy = [n for n, port in p.items() if n != "launcher" and port_open(int(port))]
        if busy:
            raise RuntimeError(f"port {p[busy[0]]} ({busy[0]}) is already in use. Close the other MOTIQ window or "
                               "terminal that is still running, then press Start again.")
        if plan["robodk"]:
            self._start_robodk(log)
        key = configure.secret_env(cfg).get("XAI_API_KEY", "")
        if key:   # the app reaches xAI through this proxy, so it never holds the key
            host = plan["host"]
            origins = {f"http://{h}:{p['expo']}" for h in ("localhost", "127.0.0.1", host)}
            self.xai.start(plan["bind"], int(p["xai_proxy"]), key, cfg["bridge_key"], origins)
            log("xAI proxy is up")
        with self.lock:
            self.services = {s.name: s for s in self._services(cfg, plan, node_exe, clear_cache)}
        order = list(self.services.values())
        for svc in order:
            log(f"starting {LABELS.get(svc.name, svc.name)}")
            svc.start()
            if svc.name in ("chooser", "controller"):   # the bridge needs both; the controller refuses a BLOCKED arm
                self._wait(svc, 90, log)
        for svc in order:
            self._wait(svc, 240 if svc.name in ("vision", "expo") else 60, log)

    def _wait(self, svc: Service, seconds: float, log) -> None:
        end = time.time() + seconds
        while time.time() < end:
            if svc.healthy():
                log(f"{LABELS.get(svc.name, svc.name)} is up")
                return
            if not svc.alive():
                tail = "\n".join(svc.tail(12))
                raise RuntimeError(f"{LABELS.get(svc.name, svc.name)} stopped while starting. Last output:\n{tail}")
            time.sleep(0.5)
        log(f"{LABELS.get(svc.name, svc.name)} is still starting (see .motiq/logs/{svc.name}.log)")

    def _start_robodk(self, log) -> None:
        exe = detect.robodk()
        if not exe:
            raise RuntimeError("MOTIQ runs on RoboDK, which isn't installed. Install it from robodk.com, "
                               "then press Try again.")
        if not port_open(20500):
            log("starting RoboDK")
            subprocess.Popen([exe], cwd=str(paths.RC), creationflags=NO_WINDOW if paths.WIN else 0)
            for _ in range(90):
                if port_open(20500):
                    break
                time.sleep(1)
            time.sleep(5)        # let it finish loading before the controller connects
        station = _station_path()
        if station and not station.exists():
            log(f"building the RoboDK station {station.name}")
            subprocess.call([str(paths.RC_PY), "-m", "robot_control.cli", "setup-station", "--config",
                             "config/robot.yaml"], cwd=str(paths.RC), creationflags=NO_WINDOW,
                            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    def stop(self, log=print) -> None:
        with self.lock:
            services = list(self.services.values())[::-1]
            self.services = {}
        self.xai.stop()
        for svc in services:
            if svc.alive():
                log(f"stopping {LABELS.get(svc.name, svc.name)}")
                svc.stop()

    def running(self) -> bool:
        with self.lock:
            return any(s.alive() for s in self.services.values())

    def status(self) -> list[dict]:
        with self.lock:
            services = list(self.services.values())
        out = []
        for s in services:
            alive = s.alive()
            out.append({"name": s.name, "label": LABELS.get(s.name, s.name), "port": s.port,
                        "state": ("up" if s.healthy() else "starting") if alive else "stopped"})
        return out

    def logs(self, name: str) -> list[str]:
        with self.lock:
            svc = self.services.get(name)
        if svc:
            return svc.tail(80)
        f = paths.LOGS / f"{re.sub(r'[^a-z]', '', name)}.log"
        return f.read_text(encoding="utf-8", errors="replace").splitlines()[-80:] if f.exists() else []
